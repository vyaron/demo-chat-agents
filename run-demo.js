async function createLinearTickets(apiKey, teamId) {
  const headers = {
    "Content-Type": "application/json",
    Authorization: apiKey,
  };

  async function createIssue(title, description, labelName) {
    const query = `
      mutation CreateIssue($input: IssueCreateInput!) {
        issueCreate(input: $input) {
          success
          issue { id identifier url }
        }
      }
    `;
    const body = JSON.stringify({
      query,
      variables: {
        input: { teamId, title, description, priority: 2 },
      },
    });

    const res = await fetch("https://api.linear.app/graphql", {
      method: "POST", headers, body,
    });
    const json = await res.json();
    const issue = json?.data?.issueCreate?.issue;
    if (!issue) throw new Error(`Linear API error: ${JSON.stringify(json)}`);
    return issue;
  }

  log("Creating Linear ticket: CHAT-FE...");
  const fe = await createIssue(
    "[CHAT] Build Chat UI",
    "Build the React chat frontend per docs/PRD.md and Figma designs.\nDefine API contract in docs/api-contract.yaml.\nWrite Vitest unit tests and Playwright e2e tests.",
    "frontend"
  );
  log(`  Created: ${fe.url}`);

  log("Creating Linear ticket: CHAT-BE...");
  const be = await createIssue(
    "[CHAT] Build Chat API + WebSocket server",
    "Implement Express + Socket.io backend per docs/api-contract.yaml.\nSet up Supabase schema (backend/supabase/schema.sql).\nWrite Vitest + Supertest API tests.",
    "backend"
  );
  log(`  Created: ${be.url}`);

  return {
    frontend: { id: fe.identifier, url: fe.url },
    backend:  { id: be.identifier, url: be.url },
  };
}

function simulateTickets() {
  return {
    frontend: { id: "CHAT-1", url: "https://linear.app/demo/issue/CHAT-1" },
    backend:  { id: "CHAT-2", url: "https://linear.app/demo/issue/CHAT-2" },
  };
}

async function runAgent({ systemPrompt, input, outputFile, doneMarker, label }) {
  // Try to use the claude CLI; fall back to simulation if not available
  try {
    execSync("claude --version", { stdio: "ignore" });
  } catch {
    warn(`claude CLI not found — simulating ${label} output.`);
    simulateAgent(label, outputFile, doneMarker);
    return;
  }

  return new Promise((resolve, reject) => {
    const command = `claude --model claude-opus-4-8 --system-prompt "${systemPrompt}" --print`;
    const child = spawn(command, {
      stdio: ["pipe", "pipe", "inherit"],
      shell: true,
    });

    let stdoutContent = "";
    child.stdout.on("data", (chunk) => {
      const text = chunk.toString();
      stdoutContent += text;
      process.stdout.write(text);
    });

    child.stdin.write(input);
    child.stdin.end();

    child.on("error", (err) => {
      // If spawn fails at runtime (e.g. ENOENT on Windows), keep demo flow alive.
      warn(`Failed to launch claude for ${label} (${err.code || err.message}) — simulating output.`);
      simulateAgent(label, outputFile, doneMarker);
      resolve();
    });

    child.on("close", (code) => {
      if (code !== 0) {
        warn(`${label} exited with code ${code} — simulating output to continue demo.`);
        simulateAgent(label, outputFile, doneMarker);
        resolve();
        return;
      }

      writeFileSync(outputFile, stdoutContent, "utf-8");
      if (stdoutContent.includes(doneMarker)) {
        log(`${label}: STATUS: DONE ✓`);
      } else {
        warn(`${label} finished but did not include '${doneMarker}' marker.`);
      }
      resolve();
    });
  });
}

function simulateAgent(label, outputFile, doneMarker) {
  log(`[SIMULATED] ${label} working...`);
  const content = `=== ${label.toUpperCase()} REPORT (SIMULATED) ===\n\n${doneMarker}\n`;
  writeFileSync(outputFile, content);
  log(`${label}: ${doneMarker} ✓`);
}

function waitForApproval(prompt) {
  return new Promise((resolve, reject) => {
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    rl.question(prompt, (answer) => {
      rl.close();
      if (answer.trim().toUpperCase() === "APPROVED") {
        log("Approved! Continuing...\n");
        resolve();
      } else {
        console.error("Aborted.");
        process.exit(1);
      }
    });
  });
}

function banner(msg) {
  const line = "═".repeat(60);
  console.log(`\n${line}\n  ${msg}\n${line}`);
}

function log(msg) {
  console.log(`  ${msg}`);
}

function warn(msg) {
  console.log(`  ⚠  ${msg}`);
}

function getArg(flag) {
  const i = process.argv.indexOf(flag);
  return i !== -1 ? process.argv[i + 1] : undefined;
}

main().catch((e) => {
  console.error("\nOrchestrator error:", e.message);
  process.exit(1);
});
