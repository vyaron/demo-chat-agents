#!/usr/bin/env node
/**
 * QuickChat Demo Orchestrator Runner
 *
 * This script drives the live demo:
 *   1. Reads PRD + Figma URL
 *   2. Generates a plan → waits for human APPROVED
 *   3. Creates Linear tickets
 *   4. Launches Frontend agent (claude CLI)
 *   5. Launches Backend agent (claude CLI)
 *
 * Usage:
 *   node run-demo.js --figma <url> --linear-team <teamId> --linear-key <apiKey>
 *
 * Env vars (alternative to flags):
 *   FIGMA_URL, LINEAR_TEAM_ID, LINEAR_API_KEY
 */

import { execSync, spawn } from "child_process";
import { readFileSync, writeFileSync, existsSync } from "fs";
import { createInterface } from "readline";





const FIGMA_URL  = process.env.FIGMA_URL  || getArg("--figma")       || "https://www.figma.com/design/tHm72cbGTItMqApwFQ7pkZ/WhatsAppUI?node-id=0-8855&m=dev";
const LINEAR_KEY = process.env.LINEAR_API_KEY || getArg("--linear-key") || "lin_api_mvsp7YObSM8Yt0zvVb3Je0ks4rA0j3N1MzkV7mx7";
const LINEAR_TEAM = process.env.LINEAR_TEAM_ID || getArg("--linear-team") || "18bf3c85-0e18-403b-bb77-2d1c1f0f8fed";

const PLAN_FILE    = "docs/PLAN.md";
const TICKETS_FILE = "docs/tickets.json";
const FE_REPORT    = "docs/frontend-agent-report.md";
const BE_REPORT    = "docs/backend-agent-report.md";

// ─────────────────────────────────────────────────────────────────────────────

async function main() {
  banner("QUICKCHAT DEMO — MULTI-AGENT ORCHESTRATOR");

  // ── Step 1: Read inputs ──────────────────────────────────────────────────
  log("Reading PRD...");
  const prd = readFileSync("docs/PRD.md", "utf-8");
  log(`PRD loaded (${prd.split("\n").length} lines)`);
  log(`Figma URL: ${FIGMA_URL}`);

  // ── Step 2: Generate Plan ────────────────────────────────────────────────
  banner("STEP 1/4 · GENERATING IMPLEMENTATION PLAN");
  const plan = generatePlan(prd, FIGMA_URL);
  writeFileSync(PLAN_FILE, plan);
  log(`Plan written to ${PLAN_FILE}`);

  console.log("\n" + "═".repeat(60));
  console.log(plan);
  console.log("═".repeat(60) + "\n");

  // ── Human Approval Gate ───────────────────────────────────────────────────
  await waitForApproval(
    `Review the plan above.\nType APPROVED to continue, or anything else to abort: `
  );

  // ── Step 3: Create Linear Tickets ────────────────────────────────────────
  banner("STEP 2/4 · CREATING LINEAR TICKETS");

  let tickets;
  if (LINEAR_KEY && LINEAR_TEAM) {
    tickets = await createLinearTickets(LINEAR_KEY, LINEAR_TEAM);
  } else {
    warn("No LINEAR_API_KEY / LINEAR_TEAM_ID — simulating ticket creation.");
    tickets = simulateTickets();
  }

  writeFileSync(TICKETS_FILE, JSON.stringify(tickets, null, 2));
  log(`CHAT-FE: ${tickets.frontend.url}`);
  log(`CHAT-BE: ${tickets.backend.url}  [Blocked — waiting for API contract]`);

  // ── Step 4: Frontend Agent ───────────────────────────────────────────────
  banner("STEP 3/4 · LAUNCHING FRONTEND AGENT");
  log("Frontend agent is building the UI and defining the API contract...\n");

  await runAgent({
    systemPrompt: "agents/frontend/CLAUDE.md",
    input: `You are the Frontend Agent. Your Linear ticket is: ${tickets.frontend.url}\nFigma designs: ${FIGMA_URL}\nPRD: docs/PRD.md\nPlan: docs/PLAN.md\nStart now. Follow your CLAUDE.md instructions exactly.`,
    outputFile: FE_REPORT,
    doneMarker: "STATUS: DONE",
    label: "Frontend Agent",
  });

  log("Frontend agent done. API contract written to docs/api-contract.yaml");

  // ── Step 5: Backend Agent ────────────────────────────────────────────────
  banner("STEP 4/4 · LAUNCHING BACKEND AGENT");
  log("Backend agent is implementing the API and WebSocket server...\n");

  await runAgent({
    systemPrompt: "agents/backend/CLAUDE.md",
    input: `You are the Backend Agent. Your Linear ticket is: ${tickets.backend.url}\nAPI contract: docs/api-contract.yaml\nPlan: docs/PLAN.md\nStart now. Follow your CLAUDE.md instructions exactly.`,
    outputFile: BE_REPORT,
    doneMarker: "STATUS: DONE",
    label: "Backend Agent",
  });

  // ── Done ─────────────────────────────────────────────────────────────────
  banner("DEMO COMPLETE ✓");
  log("App is ready!");
  log("");
  log("  1. Run Supabase schema:  backend/supabase/schema.sql");
  log("  2. Copy backend/.env.example → backend/.env  and fill credentials");
  log("  3. cd frontend && npm install && npm run dev   →  http://localhost:5173");
  log("  4. cd backend  && npm install && npm run dev   →  http://localhost:3001");
  log("");
  log("Frontend report: " + FE_REPORT);
  log("Backend report:  " + BE_REPORT);
}

// ─── Helpers ─────────────────────────────────────────────────────────────────

